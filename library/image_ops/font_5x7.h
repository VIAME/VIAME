// ----------------------------------------------------------------------------
/// Whether the glyph for \p ch has a pixel at (\p i, \p j) of its cell.
///
/// Anything outside the printable range, and anything outside the cell, is
/// blank rather than an error: text is drawn from whatever a caller has.
inline bool
font_pixel( char ch, int i, int j )
{
  if( ch < font_first || ch > font_last )
  {
    return false;
  }

  if( i < 0 || j < 0 || i >= font_width || j >= font_height )
  {
    return false;
  }

  auto const row = font_glyphs()[ ch - font_first ][ j ];

  return ( row >> ( font_width - 1 - i ) ) & 1u;
}

